//! Takes the tables that only exist in the manual (docs/prg/programmers-reference-guide.md)
//! out of it at build time, so `unc_asm::lang` can't drift from the book: the directives and
//! functions of chapter 6, the ROM costs of chapter 13, the memory map and I/O registers of Appendix B, the
//! jump table and system variables of Appendix D, and the messages of Appendix E.
//!
//! Only the rows go into the crate (as `$OUT_DIR/manual_tables.rs`), not the whole book, so
//! the WebAssembly build stays small. The cells are kept as the book writes them, markdown and
//! all; `lang` cleans them.

use std::{env, fs, path::Path};

const MANUAL: &str = "../../docs/prg/programmers-reference-guide.md";

/// (constant name, chapter heading prefix, section heading, which table in the section)
const TABLES: &[(&str, &str, &str, usize)] = &[
    ("DIRECTIVES", "## 5. ", "### Directives", 0),
    ("FUNCTIONS", "## 5. ", "### Functions", 0),
    ("ROM_COSTS", "## 12. ", "### What it costs", 0),
    ("MEMORY_MAP", "## Appendix B.", "### Memory map", 0),
    ("IO_REGISTERS", "## Appendix B.", "### I/O registers", 0),
    ("JUMP_TABLE", "## Appendix D.", "### Jump table", 0),
    ("SYSTEM_VARIABLES", "## Appendix D.", "### System variables", 0),
    ("ERRORS", "## Appendix E.", "## Appendix E.", 0),
    ("WARNINGS", "## Appendix E.", "### Warnings", 0),
];

/// Splits a markdown table row into its cells; `\|` stays in the cell.
fn cells(row: &str) -> Vec<String> {
    let inner = row.trim().trim_start_matches('|');
    let inner = inner.strip_suffix('|').unwrap_or(inner);
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut prev = ' ';
    for c in inner.chars() {
        if c == '|' && prev != '\\' {
            out.push(cur.trim().to_string());
            cur.clear();
        } else {
            cur.push(c);
        }
        prev = c;
    }
    out.push(cur.trim().to_string());
    out
}

/// The rows (header and separator left out) of table number `which` in the section headed
/// `section` inside the chapter headed `chapter...`. The section ends at the next heading of
/// its level or above.
fn table(text: &str, chapter: &str, section: &str, which: usize) -> Vec<Vec<String>> {
    let lines: Vec<&str> = text.lines().collect();
    let ch = lines.iter().position(|l| l.starts_with(chapter)).unwrap_or_else(|| panic!("manual: no chapter '{chapter}'"));
    let sec = if section == chapter {
        ch
    } else {
        ch + lines[ch..].iter().position(|l| l.trim_end() == section).unwrap_or_else(|| panic!("manual: no '{section}' in '{chapter}'"))
    };
    let level = section.chars().take_while(|&c| c == '#').count();
    let mut tables: Vec<Vec<Vec<String>>> = Vec::new();
    let mut cur: Option<Vec<Vec<String>>> = None;
    for l in &lines[sec + 1..] {
        let hashes = l.chars().take_while(|&c| c == '#').count();
        if hashes > 0 && hashes <= level && l[hashes..].starts_with(' ') {
            break;
        }
        if l.trim_start().starts_with('|') {
            cur.get_or_insert_with(Vec::new).push(cells(l));
        } else if let Some(t) = cur.take() {
            tables.push(t);
        }
    }
    tables.extend(cur);
    let t = tables.into_iter().nth(which).unwrap_or_else(|| panic!("manual: no table {which} under '{section}'"));
    t.into_iter().skip(2).collect()
}

fn main() {
    let dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let path = Path::new(&dir).join(MANUAL);
    println!("cargo:rerun-if-changed={}", path.display());
    println!("cargo:rerun-if-changed=build.rs");
    let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mut out = String::from("// Generated by build.rs from the manual. Don't edit.\n\n");
    for &(name, chapter, section, which) in TABLES {
        let rows = table(&text, chapter, section, which);
        assert!(!rows.is_empty(), "manual: the table under '{section}' is empty");
        out.push_str(&format!("pub(crate) const {name}: &[&[&str]] = &[\n"));
        for r in rows {
            let cells: Vec<String> = r.iter().map(|c| format!("{c:?}")).collect();
            out.push_str(&format!("    &[{}],\n", cells.join(", ")));
        }
        out.push_str("];\n\n");
    }
    fs::write(Path::new(&env::var("OUT_DIR").unwrap()).join("manual_tables.rs"), out).unwrap();
}
