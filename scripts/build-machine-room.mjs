#!/usr/bin/env node
// Builds the Machine Room as ONE file, for the game's bundle and for anyone to double-click:
// build/machine-room/index.html, with the CSS, the fonts, the scripts, the CodeMirror bundle
// and unc.wasm (base64) inlined, so it runs from a file:// URL with nothing fetched from the
// network or from files beside it; and build/machine-room/README.txt and LICENSES.txt.
//
// The sources are web/ as they run in development (python3 -m http.server -d web). First it
// regenerates web/bundled.js, the cassettes that come with it: the games (games/*.s,
// games/board/*.s), the samples (web/samples/) and the magazine's BASIC starter.
//
//   node scripts/build-machine-room.mjs [OUT_DIR]     # default build/machine-room
//   node scripts/build-machine-room.mjs --bundled     # only web/bundled.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WEB = path.join(ROOT, 'web');
const rd = (p) => fs.readFileSync(path.join(WEB, p), 'utf8');

// ---------- web/bundled.js ----------
// About lines for the games, from the showcase's pitches; everything else gets the first
// line of its own header comment.
const ABOUT = {
  snake: 'The classic, on a 40 × 25 text screen. Eat, grow, don\'t bite yourself.',
  stack: 'A falling-block puzzle in a 9-wide well. Every 8th piece is a bomb.',
  orbit: 'Shoot the drifting rocks around a small planet that pulls on everything.',
  debug: 'Bugs march down the screen in formation. You\'re the cursor. Fix them.',
  aurora: 'Fly low over the fells at night, under the northern lights. The video board\'s demonstration cassette.',
  frosthall: 'Walk round a hall of timber, stone and ice, in three dimensions, at 1 MHz. For the NIECE, the prototype graphics chip.',
  tracker: 'A three-voice tracker for the AUNT, the sound chip, with four tunes on it. RETURN plays, T is the next tune.',
};
const TITLE = { sun: 'SUN OVER A HOUSE', tracker: 'MUSIC TRACKER' };
function header(src, mark) {
  const first = src.split('\n').find((l) => l.startsWith(mark));
  return first ? first.slice(mark.length).trim() : '';
}
function bundled() {
  const list = [];
  const add = (file, group, extra = {}) => {
    const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
    const name = path.basename(file);
    const id = name.replace(/\.(s|bas)$/, '');
    const bas = name.endsWith('.bas');
    list.push({
      id, group, file: name,
      title: extra.title || TITLE[id] || id.replace(/[-_]/g, ' ').toUpperCase(),
      about: ABOUT[id] || header(src, bas ? '#' : ';'),
      ram: /\b64K\b|UNC 64 \(64K\)/.test(src.split('\n').slice(0, 3).join('\n')) ? 64 : 16,
      board: file.includes('games/board/'),
      niece: file.includes('games/niece/'),
      source: src,
    });
  };
  const ls = (dir, ext) => fs.readdirSync(path.join(ROOT, dir)).filter((f) => f.endsWith(ext)).sort().map((f) => `${dir}/${f}`);
  const ORDER = ['snake', 'stack', 'orbit', 'debug']; // as on the uncle's stand
  const rank = (f) => { const i = ORDER.indexOf(path.basename(f, '.s')); return i < 0 ? 99 : i; };
  for (const f of ls('games', '.s').sort((a, b) => rank(a) - rank(b))) add(f, 'Games');
  for (const f of ls('games/board', '.s')) add(f, 'Games');
  for (const f of ls('games/niece', '.s')) add(f, 'Games');
  for (const f of ls('games/sound', '.s')) add(f, 'Games');
  for (const f of ls('web/samples', '.s')) add(f, 'Samples');
  for (const f of ls('web/samples', '.bas')) add(f, 'BASIC');
  const out = '// Generated by scripts/build-machine-room.mjs from games/ (and games/board/, games/niece/, games/sound/) and web/samples/. Do not edit.\n'
    + `window.UNC_BUNDLED = ${JSON.stringify(list, null, 0)};\n`;
  fs.writeFileSync(path.join(WEB, 'bundled.js'), out);
  console.log(`web/bundled.js: ${list.map((g) => g.id).join(', ')}`);
}

// ---------- the one file ----------
// Text inside <script> must not close it early.
const safe = (js) => js.replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');

// The vendored ES module as a classic script: its top-level names stay inside a function,
// and its `export{a as B, ...}` becomes window.UNCCodeMirror = { B: a, ... }.
function vendorGlobal() {
  const src = rd('vendor/codemirror.js');
  const m = /export\s*\{([^}]*)\}\s*;?\s*$/.exec(src);
  if (!m) throw new Error('web/vendor/codemirror.js: no export list at its end');
  const pairs = m[1].split(',').map((s) => s.trim()).filter(Boolean).map((s) => {
    const [local, as] = s.split(/\s+as\s+/);
    return `${as || local}:${local}`;
  });
  return `window.UNCCodeMirror=(()=>{${src.slice(0, m.index)}\nreturn{${pairs.join(',')}};})();`;
}
// editor.js's import from the bundle as a destructure of that global.
function editorClassic() {
  const src = rd('editor.js');
  const re = /import\s*\{([^}]*)\}\s*from\s*'\.\/vendor\/codemirror\.js';/;
  if (!re.test(src)) throw new Error('web/editor.js: no import from ./vendor/codemirror.js');
  return src.replace(re, (_, names) => `const {${names.replace(/\s+as\s+/g, ': ')}} = window.UNCCodeMirror;`);
}

function build(outDir) {
  let html = rd('index.html');
  // the stylesheet, with its fonts as data
  let css = rd('style.css').replace(/url\((['"]?)fonts\/([\w.-]+\.woff2)\1\)/g, (_, q, f) => {
    const b64 = fs.readFileSync(path.join(WEB, 'fonts', f)).toString('base64');
    return `url(data:font/woff2;base64,${b64})`;
  });
  if (/url\((?!data:)/.test(css)) throw new Error('style.css still points at a file');
  html = html.replace('<link rel="stylesheet" href="style.css">', () => `<style>\n${css}</style>`);
  // classic scripts, inlined; the machine itself as base64 before app.js
  html = html.replace(/<script src="([\w.-]+\.js)"><\/script>/g, (_, f) => {
    const pre = f === 'app.js'
      ? `<script>window.UNC_WASM_B64="${fs.readFileSync(path.join(WEB, 'unc.wasm')).toString('base64')}";</script>\n`
      : '';
    return pre + `<script>\n${safe(rd(f))}</script>`;
  });
  // the editor: CodeMirror as a global, then editor.js as an inline module (it uses top-level await)
  html = html.replace('<script type="module" src="editor.js"></script>', () =>
    `<script>\n${safe(vendorGlobal())}</script>\n<script type="module">\n${safe(editorClassic())}</script>`);
  if (/<(script|link|img)[^>]+(src|href)="(?!data:|#)/i.test(html)) throw new Error('index.html still loads a file');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'index.html'), html);
  fs.writeFileSync(path.join(outDir, 'README.txt'), README);
  fs.copyFileSync(path.join(ROOT, 'docs', 'machine-room.md'), path.join(outDir, 'GUIDE.md'));
  fs.writeFileSync(path.join(outDir, 'LICENSES.txt'), `The Machine Room includes CodeMirror and its Vim mode (MIT) and two font families (SIL OFL 1.1).\n\n${rd('fonts/LICENSE.md')}\n\n${rd('vendor/LICENSES.txt')}`);
  console.log(`${path.relative(ROOT, outDir) || outDir}/index.html: ${(html.length / 1024).toFixed(0)} KB`);
}

const README = `UNC 64 MACHINE ROOM
===================

The UNC 64 on your computer, for writing programs for it: the real emulator, an
assembler, a debugger and a tape deck, in one web page. It runs entirely in your
browser. Nothing to install, no internet, nothing leaves your computer.

OPEN IT
  Double-click index.html. It opens in your web browser (a current Chrome, Edge,
  Firefox or Safari). If it opens in something else, drag it onto a browser window.

WHAT YOU CAN DO
  - Write UNC assembly (.s) or UNC BASIC (.bas) and press Run (Ctrl+Enter).
  - Step through it in the debugger: registers, disassembly, breakpoints, memory.
  - Browse the cassettes: the games that come with the UNC 64, the samples, yours.
  - Put a cassette in the tape deck, type LOAD and press PLAY, as on the machine.
  - Save your program as a cassette (Save), or download it (Export).
  Help, in the page, explains the rest; GUIDE.md is the full guide. LICENSES.txt has the licences of what's
  inside (CodeMirror, the fonts).

CASSETTES
  A cassette is a .unc.png file: a picture of the tape, with the program (and its
  source, if you like) inside it. Pass the file on as it is and it still loads;
  a site that re-encodes pictures keeps the face and drops the tape.
  A .tap file is a bare tape, without the picture; it works too.

  Your library is kept in this browser. To keep a cassette for good, or to give it
  to someone, Export it: that downloads the .unc.png.

BRING THEM INTO THE GAME
  First turn on My tapes in the game's pause menu (Settings, Assembler). The game
  then reads cassettes from one folder, which it makes when you turn it on:

    macOS     ~/Documents/UNC 64/Cassettes
    Windows   C:\\Users\\<you>\\Documents\\UNC 64\\Cassettes
    Linux     ~/Documents/UNC 64/Cassettes   (your Documents folder)

  Put your .unc.png or .tap files there, or drop them on the game's window (they're
  copied there). "Open the folder", beside My tapes, opens it. Your cassettes turn up
  in the shoebox on the desk: put one in the deck, type LOAD, press PLAY.

To open a cassette someone gave you here: Open, or drop it on the page.
`;

const args = process.argv.slice(2);
bundled();
if (!args.includes('--bundled')) build(path.resolve(args.find((a) => !a.startsWith('--')) || path.join(ROOT, 'build', 'machine-room')));
